// The test version used to install itself for offline play. This worker
// replaces the old one: it deletes the saved game files and removes itself,
// so phones that installed the test version open this page instead.
self.addEventListener("install", () => self.skipWaiting());
self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) await caches.delete(key);
    await self.registration.unregister();
    for (const client of await self.clients.matchAll({ type: "window" })) client.navigate(client.url);
  })());
});
